/** Replace a marked region in a markdown file, failing closed if the markers are gone. */
function injectRegion(file, startMarker, endMarker, body, label) {
  const path = join(root, file);
  let src;
  try {
    src = readFileSync(path, "utf8");
  } catch {
    return; // the file is optional; nothing to keep in sync
  }
  const s = src.indexOf(startMarker);
  const e = src.indexOf(endMarker);
  if (s === -1 || e === -1 || e < s) {
    console.error(
      `✗ sync-component-derived: ${label} markers missing or misordered in ${file}\n  expected "${startMarker}" then "${endMarker}"`,
    );
    process.exit(1);
  }
  const next =
    src.slice(0, s + startMarker.length) + "\n" + body + "\n" + src.slice(e);
  if (next === src) return;
  if (check) {
    console.error(
      `✗ stale generated contract surface: ${file} (${label} region)`,
    );
    process.exit(1);
  }
  writeFileSync(path, next);
  console.log(`✓ wrote ${file} (${label} region)`);
}

injectRegion("AGENTS.md", NUMBERS_START, NUMBERS_END, numbersBody, "NUMBERS");
injectRegion(
  "README.md",
  INVENTORY_START,
  INVENTORY_END,
  inventoryBody,
  "INVENTORY",
);

let stale = 0;
for (const [relative, expected] of outputs) {
  const absolute = join(root, relative);
  let actual;
  try {
    actual = readFileSync(absolute, "utf8");
  } catch {
    actual = undefined;
  }
  if (actual === expected) continue;
  if (check) {
    stale++;
    console.error(`✗ stale generated contract surface: ${relative}`);
  } else {
    writeFileSync(absolute, expected);
    console.log(`✓ wrote ${relative}`);
  }
}

if (stale) process.exit(1);
if (check)
  console.log(
    `✓ component-derived surfaces are current (${outputs.size} files; ${allRecords.length}/${allRecords.length} items)`,
  );
