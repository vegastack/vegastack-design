#!/usr/bin/env node
// Mirror the lucide-animated registry (https://lucide-animated.com) into the VegaStack private
// registry so any animated icon is installable via `shadcn add @vegastack/<icon>` and consumable
// through `AnimatedIcon` from @vegastack/design/icons.
//
// What it does (idempotent, LOCAL — no publish/push):
//   1. fetch https://lucide-animated.com/r/registry.json  → the list of items
//   2. for each (concurrency-limited): fetch /r/<name>.json → the component source
//   3. transform: rewrite `@/lib/utils` → `@vegastack/design`, prepend an upstream-attribution
//      header; assert NO hex / raw-palette (keep the token-only color guarantee)
//   4. write canonical source → packages/ui/registry/ui/icons/<name>.tsx
//   5. rewrite the lucide-animated section of packages/ui/registry.json (items carrying
//      meta.source === 'lucide-animated'), preserving the hand-authored component items untouched
//
// After this, run the normal `npm run registry:build` — shadcn build inlines each source, then
// registry-stamp/registry-header/verify-headers stamp + verify integrity uniformly.
//
// Flags: --limit N (mirror only the first N, for validation), --offset N.
import { mkdirSync, writeFileSync, readFileSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const REGISTRY = 'https://lucide-animated.com/r';
const SRC_DIR = 'packages/ui/registry/ui/icons';
// The docs copy-in (target `@ui/icons/<name>.tsx`). registry-header SYNCS an existing copy-in from the
// stamped source but never CREATES one, so the mirror writes it here (registry-build then re-syncs it
// byte-identical after stamping the provenance header onto the source).
const COPY_DIR = 'apps/docs/components/ui/icons';
const REGISTRY_JSON = 'packages/ui/registry.json';
const SOURCE_TAG = 'lucide-animated';
const CONCURRENCY = 12;

const args = process.argv.slice(2);
const limit = Number(args[args.indexOf('--limit') + 1]) || Infinity;
const offset = Number(args[args.indexOf('--offset') + 1]) || 0;

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

async function fetchJson(url, tries = 3) {
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (err) {
      if (i === tries - 1) throw new Error(`fetch ${url}: ${err.message}`);
    }
  }
}

// Run async `fn` over `items` with a fixed worker pool (bounded concurrency).
async function pool(items, size, fn) {
  const out = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(size, items.length) }, async () => {
      while (next < items.length) {
        const i = next++;
        out[i] = await fn(items[i], i);
      }
    }),
  );
  return out;
}

function transform(content, name) {
  let c = content;
  // 1. rewrite the utils import to the published VegaStack package (matches every other component).
  c = c.replace(/(['"])@\/lib\/utils\1/g, '"@vegastack/design"');
  // 2. fail-closed color guarantee — mirrored icons must be token/currentColor only.
  const hex = c.match(/#[0-9a-fA-F]{3,8}\b/);
  if (hex) throw new Error(`${name}: hex color ${hex[0]} in mirrored icon (expected currentColor only)`);
  if (/(?:bg|text|border|stroke|fill)-(?:red|orange|amber|green|blue|purple|neutral|gray|zinc|slate|stone)-\d{2,3}\b/.test(c)) {
    throw new Error(`${name}: raw palette utility in mirrored icon`);
  }
  // 3. upstream attribution (registry-header later prepends its own `// @vegastack …` provenance line).
  const header =
    `// Mirrored from lucide-animated (https://lucide-animated.com/r/${name}.json) — MIT.\n` +
    `// Generated by tooling/mirror-animated-icons.mjs — do NOT hand-edit; re-run the mirror to update.\n\n`;
  return header + c.trimStart() + '\n';
}

function buildItem(name) {
  return {
    // Item names are `icon-<lucide-name>` — bare lucide names collide with component items
    // (first real case: the Terminal marketing component vs the terminal icon). File paths and
    // @ui/icons/ targets keep the raw lucide name; only the INSTALL name is prefixed.
    name: `icon-${name}`,
    type: 'registry:ui',
    title: pascal(name),
    description: `Animated ${name.replace(/-/g, ' ')} icon — Motion-powered (hover or imperative trigger).`,
    categories: ['icons'],
    dependencies: ['motion', '@vegastack/design@^0.1.0'],
    registryDependencies: [],
    files: [
      {
        path: `${SRC_DIR}/${name}.tsx`,
        type: 'registry:ui',
        target: `@ui/icons/${name}.tsx`,
      },
    ],
    meta: { version: '0.1.0', source: SOURCE_TAG, upstream: `${REGISTRY}/${name}.json`, license: 'MIT' },
  };
}

// ── fetch the index ──────────────────────────────────────────────────────────────────────────────
const index = await fetchJson(`${REGISTRY}/registry.json`);
// Dedupe — the upstream index contains a duplicate entry (e.g. `chess-bishop` is listed twice).
let names = [...new Set(index.items.map((i) => i.name))].sort();
names = names.slice(offset, offset === 0 && limit !== Infinity ? limit : offset + limit);
console.log(`lucide-animated: ${index.items.length} items upstream; mirroring ${names.length}`);

// ── guard against name collisions with the hand-authored component registry ────────────────────────
const registry = JSON.parse(readFileSync(REGISTRY_JSON, 'utf8'));
const componentNames = new Set(registry.items.filter((i) => i.meta?.source !== SOURCE_TAG).map((i) => i.name));
const collisions = names.filter((n) => componentNames.has(`icon-${n}`));
if (collisions.length) throw new Error(`name collision with components: ${collisions.join(', ')}`);

// ── fetch + transform + write each source file ─────────────────────────────────────────────────────
mkdirSync(SRC_DIR, { recursive: true });
mkdirSync(COPY_DIR, { recursive: true });
let written = 0;
await pool(names, CONCURRENCY, async (name) => {
  const item = await fetchJson(`${REGISTRY}/${name}.json`);
  const file = item.files?.[0];
  if (!file?.content) throw new Error(`${name}: upstream item has no file content`);
  const out = transform(file.content, name);
  writeFileSync(join(SRC_DIR, `${name}.tsx`), out);
  writeFileSync(join(COPY_DIR, `${name}.tsx`), out); // copy-in (re-synced + header-stamped by registry-build)
  written++;
  if (written % 50 === 0) console.log(`  …${written}/${names.length}`);
});

// ── rewrite the mirrored section of registry.json (keep component items untouched) ─────────────────
const kept = registry.items.filter((i) => i.meta?.source !== SOURCE_TAG);
// when mirroring a partial batch, retain previously-mirrored items not in this batch IF their source
// file still exists (so a --limit run doesn't orphan registry entries).
const batch = new Set(names);
const priorMirrored = registry.items.filter(
  (i) =>
    i.meta?.source === SOURCE_TAG &&
    !batch.has(i.name.replace(/^icon-/, '')) &&
    existsSync(join(SRC_DIR, `${i.name.replace(/^icon-/, '')}.tsx`)),
);
const mirrored = [...priorMirrored, ...names.map(buildItem)].sort((a, b) => a.name.localeCompare(b.name));
registry.items = [...kept, ...mirrored];
writeFileSync(REGISTRY_JSON, JSON.stringify(registry, null, 2) + '\n');

// ── prune orphaned source files (icons removed upstream / not in registry) ─────────────────────────
const valid = new Set(mirrored.map((i) => i.name.replace(/^icon-/, '')));
let pruned = 0;
for (const d of [SRC_DIR, COPY_DIR]) {
  if (!existsSync(d)) continue;
  for (const f of readdirSync(d)) {
    if (f.endsWith('.tsx') && !valid.has(f.replace(/\.tsx$/, ''))) {
      rmSync(join(d, f));
      pruned++;
    }
  }
}

console.log(
  `✓ mirror: ${written} source(s) written, registry.json now has ${mirrored.length} ${SOURCE_TAG} item(s) + ${kept.length} component(s)` +
    (pruned ? `, pruned ${pruned} orphan(s)` : ''),
);
