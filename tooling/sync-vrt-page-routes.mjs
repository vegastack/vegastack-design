#!/usr/bin/env node

import {
  existsSync,
  lstatSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

import { ROOT } from "./lib/change-set.mjs";

const OUTPUT = join(ROOT, "apps/docs/vrt/page-routes.generated.ts");

function repoPath(root, path) {
  return relative(root, path).split(sep).join("/");
}

function contentRoutes(root) {
  const content = join(root, "apps/docs/content");
  const routes = ["/"];
  const walk = (directory) => {
    const stat = lstatSync(directory);
    if (stat.isSymbolicLink() || !stat.isDirectory())
      throw new Error(
        `VRT content root is not a regular directory: ${repoPath(root, directory)}`,
      );
    for (const name of readdirSync(directory).sort()) {
      const path = join(directory, name);
      const entry = lstatSync(path);
      if (entry.isSymbolicLink())
        throw new Error(
          `VRT content authority rejects symlink: ${repoPath(root, path)}`,
        );
      if (entry.isDirectory()) {
        walk(path);
        continue;
      }
      if (!entry.isFile() || !name.endsWith(".mdx")) continue;
      const relativeContent = relative(content, path).split(sep).join("/");
      if (!/^(?:docs|internal)\/.+\.mdx$/.test(relativeContent))
        throw new Error(
          `unroutable MDX authority path: ${repoPath(root, path)}`,
        );
      if (/[\[\]]/.test(relativeContent))
        throw new Error(
          `dynamic MDX route requires an explicit VRT model: ${repoPath(root, path)}`,
        );
      const route = `/${relativeContent.replace(/\.mdx$/, "").replace(/\/index$/, "")}`;
      routes.push(route);
    }
  };
  walk(content);
  const sorted = [...new Set(routes)].sort();
  if (sorted.length !== routes.length)
    throw new Error("duplicate routable MDX route in VRT authority");
  return sorted;
}

export function generatedVrtPageRoutes({ root = ROOT } = {}) {
  const routes = contentRoutes(root);
  return {
    routes,
    source: `// GENERATED by tooling/sync-vrt-page-routes.mjs from every routable apps/docs/content/**/*.mdx.\n// DO NOT EDIT. Unknown, dynamic, or symlinked content fails generation instead of disappearing.\n\nexport const VRT_PAGE_ROUTES = ${JSON.stringify(routes, null, 2)} as const;\n`,
  };
}

export function assertVrtPageRoutesCurrent({ root = ROOT } = {}) {
  const generated = generatedVrtPageRoutes({ root });
  const output = join(root, "apps/docs/vrt/page-routes.generated.ts");
  const current = existsSync(output) ? readFileSync(output, "utf8") : null;
  if (current !== generated.source)
    throw new Error(
      "generated VRT page authority is missing or stale; run `node tooling/sync-vrt-page-routes.mjs`",
    );
  return generated;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const generated = generatedVrtPageRoutes();
  if (check) {
    try {
      assertVrtPageRoutesCurrent();
    } catch {
      console.error(
        "sync-vrt-page-routes: generated route authority is stale; run `node tooling/sync-vrt-page-routes.mjs`",
      );
      process.exit(1);
    }
  } else writeFileSync(OUTPUT, generated.source);

  console.log(
    `✓ VRT page routes: ${generated.routes.length} routable MDX/root page(s) are exact`,
  );
}
